/* ─── 현재 언어 상태 ─── */
let currentLang = localStorage.getItem('wy_lang') || 'ko';

/* ─── 번역 함수 ─── */
function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || (I18N['ko'] && I18N['ko'][key]) || key;
}

/* ─── 언어 전환 메인 함수 ─── */
function setLang(lang) {
  if (!I18N[lang]) return;
  currentLang = lang;
  localStorage.setItem('wy_lang', lang);

  // 버튼 활성화 상태 갱신
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  // data-i18n 속성으로 텍스트 교체
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    const val = t(key);
    if (!val) return;
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = val;
    } else {
      // footer-note: wy_footer.note가 있으면 건드리지 않음
      if (el.id === 'footer-note') {
        try {
          const f = JSON.parse(localStorage.getItem('wy_footer') || '{}');
          if (f.note) return; // 관리자 설정 우선
        } catch(e) {}
      }
      el.textContent = val;
    }
  });

  // data-i18n-html 속성 (줄바꿈 포함)
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.dataset.i18nHtml;
    const val = t(key);
    if (val) el.innerHTML = val.replace(/\n/g, '<br>');
  });

  // html lang 속성 변경
  const langMap = { ko:'ko', en:'en', ja:'ja', zh:'zh-CN' };
  document.documentElement.lang = langMap[lang] || 'ko';

  // title 변경
  const titles = {
    ko: '왕열 Wang Yeul — 현대 한국화',
    en: 'Wang Yeul — Contemporary Korean Painting',
    ja: 'Wang Yeul — 現代韓国画',
    zh: 'Wang Yeul — 当代韩国画'
  };
  document.title = titles[lang] || titles.ko;
}

/* ─── 초기화 ─── */
document.addEventListener('DOMContentLoaded', function() {
  setLang(currentLang);
});
